    def diagnostics(self) -> dict[str, object]:
        messages = list(self.diagnostics_messages)
        if not self.title or self.title == "CPJ Web App":
            messages.append({"level": "warning", "area": "seo", "message": "Set a specific page title."})
        if len(self.description.strip()) < 20:
            messages.append({"level": "warning", "area": "seo", "message": "Meta description is short or missing."})
        if self.seen_h1 == 0:
            messages.append({"level": "warning", "area": "accessibility", "message": "Page has no h1 heading."})
        if self.seen_h1 > 1:
            messages.append({"level": "info", "area": "accessibility", "message": "Page has multiple h1 headings; verify document outline."})
        for upload in self.uploads:
            if not upload.get("accept"):
                messages.append({"level": "info", "area": "security", "message": f"Upload {upload.get('name')} allows any content type."})
        guarded_paths = [guard.get("path") for guard in self.guards]
        for upload in self.uploads:
            if upload.get("path") not in guarded_paths:
                messages.append({"level": "warning", "area": "security", "message": f"Upload endpoint {upload.get('path')} is not guarded."})
        declared_services = set(self.services)
        injected_services = {name for route in self.api_routes for name in route.get("inject", [])}
        for name in sorted(injected_services - declared_services):
            messages.append({"level": "warning", "area": "dependency-injection", "message": f"API injects undefined service {name}."})
        if self.migrations and not self.stores:
            messages.append({"level": "warning", "area": "database", "message": "Migrations are declared without stores."})
        return {
            "title": self.title,
            "summary": {
                "errors": sum(1 for item in messages if item["level"] == "error"),
                "warnings": sum(1 for item in messages if item["level"] == "warning"),
                "info": sum(1 for item in messages if item["level"] == "info"),
            },
            "messages": messages,
        }

