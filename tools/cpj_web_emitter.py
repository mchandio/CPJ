class WebEmitter:
    """Emit a CPJ module as a standalone HTML document."""

    def __init__(self):
        self.title = "CPJ Web App"
        self.description = "Standalone web application generated by CPJ."
        self.theme = dict(DEFAULT_THEME)
        self.nav_items: list[tuple[str, str]] = []
        self.body_parts: list[str] = []
        self.states: dict[str, str] = {}
        self.components: dict[str, str] = {}
        self.routes: list[dict[str, str]] = []
        self.api_routes: list[dict[str, object]] = []
        self.models: dict[str, list[dict[str, str | bool]]] = {}
        self.custom_css: list[str] = []
        self.custom_js: list[str] = []
        self.pwa: dict[str, object] | None = None
        self.uploads: list[dict[str, object]] = []
        self.stores: dict[str, dict[str, object]] = {}
        self.middleware: list[dict[str, object]] = []
        self.pipelines: list[dict[str, object]] = []
        self.guards: list[dict[str, object]] = []
        self.services: dict[str, dict[str, object]] = {}
        self.migrations: list[dict[str, object]] = []
        self.templates: dict[str, str] = {}
        self.bundle: dict[str, object] = {}
        self.marketplace: dict[str, object] = {"name": "CPJ Marketplace", "registry": "local", "plugins": [], "hooks": {}}
        self.diagnostics_messages: list[dict[str, str]] = []
        self.seen_h1 = 0
        self.server_host = "127.0.0.1"
        self.server_port = 8080
        self.cms: dict[str, object] | None = None

    def emit(self, node: Module) -> str:
        web_blocks = [item for item in node.items if isinstance(item, WebBlock)]

        if web_blocks:
            for block in web_blocks:
                self._emit_web_block(block)
        else:
            self._emit_fallback(node.items)

        return self._document()

    def _emit_web_block(self, block: WebBlock) -> None:
        rendered, _ = self._emit_lines(block.lines, 0)
        self.body_parts.append(rendered)

    def _emit_fallback(self, items: Iterable[object]) -> None:
        output = []
        for item in items:
            if isinstance(item, Print) and isinstance(item.expr, Str):
                output.append(self._tag("p", item.expr.s))

        if not output:
            output.append(
                self._tag(
                    "p",
                    "No web block found. Add `web { ... }` to emit a browser page.",
                    "cpj-muted",
                )
            )

        self.body_parts.append(
            self._block(
                "section",
                [
                    self._tag("h1", self.title),
                    *output,
                ],
                {"class": "cpj-section cpj-section--hero"},
            )
        )

    def _emit_lines(self, lines: list[str], start: int, context: str | None = None) -> tuple[str, int]:
        parts = []
        index = start

        while index < len(lines):
            line = lines[index].strip()
            index += 1

            if not line or line.startswith("#") or line.startswith("//"):
                continue
            if line == "}":
                break

            if line.endswith("{"):
                command = line[:-1].strip()
                if self._raw_block_kind(command) in {
                    "api",
                    "animation",
                    "cms",
                    "container",
                    "guard",
                    "migration",
                    "middleware",
                    "model",
                    "pipeline",
                    "service",
                    "store",
                    "upload",
                    "bundle",
                    "marketplace",
                }:
                    raw_lines, index = self._collect_raw_block(lines, index)
                    rendered = self._emit_raw_block(command, raw_lines)
                else:
                    inner, index = self._emit_lines(lines, index, self._child_context(command, context))
                    rendered = self._emit_block(command, inner)
            else:
                rendered = self._emit_statement(line, context)

            if rendered:
                parts.append(rendered)

        return "\n".join(parts), index

    def _raw_block_kind(self, command: str) -> str:
        tokens = self._split(command)
        return tokens[0].lower() if tokens else ""

    def _collect_raw_block(self, lines: list[str], start: int) -> tuple[list[str], int]:
        raw_lines = []
        index = start
        depth = 1

        while index < len(lines) and depth > 0:
            line = lines[index].strip()
            index += 1

            opens = line.count("{")
            closes = line.count("}")
            depth += opens - closes

            if depth <= 0 and line == "}":
                continue
            raw_lines.append(line)

        return raw_lines, index

    def _child_context(self, command: str, context: str | None) -> str | None:
        tokens = self._split(command)
        if tokens and tokens[0].lower() == "form":
            return "form"
        return context

    def _emit_block(self, command: str, inner: str) -> str:
        tokens = self._split(command)
        if not tokens:
            return inner

        kind = tokens[0].lower()
        name = tokens[1] if len(tokens) > 1 else kind

        if kind in {"section", "hero"}:
            section_name = name if kind == "section" else "hero"
            section_id = self._slug(section_name)
            classes = f"cpj-section cpj-section--{section_id}"
            return self._wrap("section", inner, {"id": section_id, "class": classes})

        if kind == "grid":
            return self._wrap("div", inner, {"class": "cpj-grid"})

        if kind == "card":
            title = tokens[1] if len(tokens) > 1 else ""
            heading = self._tag("h3", title) if title else ""
            return self._wrap("article", heading + inner, {"class": "cpj-card"})

        if kind == "component":
            component_name = self._slug(name)
            self.components[component_name] = inner
            return ""

        if kind == "template":
            template_name = self._slug(name)
            self.templates[template_name] = inner
            self.components[template_name] = inner
            return ""

        if kind == "route":
            route_path = name if name.startswith("/") else f"/{name}"
            template_name = self._template_from_tokens(tokens[2:])
            if template_name:
                inner = self._apply_template(template_name, inner)
            self.routes.append({"path": route_path, "html": inner})
            return ""

        if kind == "form":
            form_id = self._slug(name)
            attrs = self._form_attrs(form_id, tokens[2:])
            return self._wrap(
                "form",
                inner,
                attrs,
            )

        if kind in {"header", "main", "footer", "aside", "nav"}:
            return self._wrap(kind, inner, {"class": f"cpj-{kind}"})

        return self._wrap("div", inner, {"class": f"cpj-block cpj-block--{self._slug(kind)}"})

    def _emit_raw_block(self, command: str, raw_lines: list[str]) -> str:
        tokens = self._split(command)
        if not tokens:
            return ""

        kind = tokens[0].lower()
        name = tokens[1] if len(tokens) > 1 else kind

        if kind == "api":
            path = name if name.startswith("/") else f"/{name}"
            payload: dict[str, object] = {}
            method = "GET"
            inject: list[str] = []
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                if parts[0].lower() == "method" and len(parts) > 1:
                    method = parts[1].upper()
                elif parts[0].lower() == "json" and len(parts) > 2:
                    payload[self._slug(parts[1])] = self._coerce_value(" ".join(parts[2:]))
                elif parts[0].lower() == "inject" and len(parts) > 1:
                    inject.extend(self._slug(part) for part in parts[1:])
            self.api_routes.append({"path": path, "method": method, "json": payload, "inject": inject})
            return ""

        if kind == "service":
            service_name = self._slug(name)
            service: dict[str, object] = {"name": service_name, "values": {}, "env": {}, "singleton": True}
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower().replace("-", "_")
                if command == "value" and len(parts) > 2:
                    service["values"][self._slug(parts[1])] = self._coerce_value(" ".join(parts[2:]))
                elif command == "env" and len(parts) > 2:
                    service["env"][self._slug(parts[1])] = {
                        "name": parts[2],
                        "default": self._coerce_value(" ".join(parts[3:])) if len(parts) > 3 else "",
                    }
                elif command == "singleton" and len(parts) > 1:
                    service["singleton"] = bool(self._coerce_value(parts[1]))
            self.services[service_name] = service
            return ""

        if kind == "model":
            fields = []
            for line in raw_lines:
                parts = self._split(line)
                if len(parts) >= 3 and parts[0].lower() == "field":
                    fields.append(
                        {
                            "name": self._slug(parts[1]),
                            "type": parts[2],
                            "required": any(part.lower() == "required" for part in parts[3:]),
                        }
                    )
            self.models[self._slug(name)] = fields
            return ""

        if kind == "store":
            store_name = self._slug(name)
            store: dict[str, object] = {
                "name": store_name,
                "path": f"/api/store/{store_name}",
                "fields": [],
                "seed": [],
            }
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower()
                if command == "path" and len(parts) > 1:
                    store["path"] = parts[1]
                elif command == "field" and len(parts) >= 3:
                    store["fields"].append(
                        {
                            "name": self._slug(parts[1]),
                            "type": parts[2],
                            "required": any(part.lower() == "required" for part in parts[3:]),
                        }
                    )
                elif command == "seed" and len(parts) > 2:
                    row = {}
                    index = 1
                    while index + 1 < len(parts):
                        row[self._slug(parts[index])] = self._coerce_value(parts[index + 1])
                        index += 2
                    if row:
                        store["seed"].append(row)
            self.stores[store_name] = store
            return ""

        if kind == "migration":
            migration_name = self._slug(name)
            migration: dict[str, object] = {"name": migration_name, "store": "", "add_fields": [], "indexes": []}
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower().replace("-", "_")
                if command == "store" and len(parts) > 1:
                    migration["store"] = self._slug(parts[1])
                elif command in {"add_field", "field"} and len(parts) >= 3:
                    field = {
                        "name": self._slug(parts[1]),
                        "type": parts[2],
                        "required": any(part.lower() == "required" for part in parts[3:]),
                    }
                    migration["add_fields"].append(field)
                elif command == "index" and len(parts) > 1:
                    migration["indexes"].append(
                        {
                            "field": self._slug(parts[1]),
                            "unique": any(part.lower() == "unique" for part in parts[2:]),
                        }
                    )
            if not migration["store"]:
                migration["store"] = migration_name
            store = self.stores.get(str(migration["store"]))
            if store:
                existing = {field["name"] for field in store.get("fields", [])}
                for field in migration["add_fields"]:
                    if field["name"] not in existing:
                        store["fields"].append(field)
            self.migrations.append(migration)
            return ""

        if kind == "upload":
            upload_name = self._slug(name)
            upload: dict[str, object] = {
                "name": upload_name,
                "path": f"/api/uploads/{upload_name}",
                "dir": f"uploads/{upload_name}",
                "accept": [],
                "max_bytes": 5 * 1024 * 1024,
            }
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower().replace("-", "_")
                if command == "path" and len(parts) > 1:
                    upload["path"] = parts[1]
                elif command in {"dir", "directory"} and len(parts) > 1:
                    upload["dir"] = parts[1]
                elif command == "accept" and len(parts) > 1:
                    upload["accept"] = [item.strip() for item in " ".join(parts[1:]).split(",") if item.strip()]
                elif command in {"max", "max_bytes", "maxbytes"} and len(parts) > 1:
                    upload["max_bytes"] = int(parts[1])
            self.uploads.append(upload)
            return ""

        if kind == "middleware":
            middleware: dict[str, object] = {
                "name": self._slug(name),
                "headers": {},
                "cors": "",
                "log": False,
                "request_id": False,
                "require_headers": [],
            }
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower().replace("-", "_")
                if command == "header" and len(parts) > 2:
                    middleware["headers"][" ".join(parts[1:-1])] = parts[-1]
                elif command == "cors":
                    middleware["cors"] = parts[1] if len(parts) > 1 else "*"
                elif command == "log" and len(parts) > 1:
                    middleware["log"] = bool(self._coerce_value(parts[1]))
                elif command == "request_id" and len(parts) > 1:
                    middleware["request_id"] = bool(self._coerce_value(parts[1]))
                elif command == "require_header" and len(parts) > 2:
                    middleware["require_headers"].append(self._require_header(parts[1:]))
            self.middleware.append(middleware)
            return ""

        if kind == "pipeline":
            pipeline: dict[str, object] = {
                "name": self._slug(name),
                "uses": [],
                "headers": {},
                "cors": "",
                "log": False,
                "request_id": False,
                "require_headers": [],
            }
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower().replace("-", "_")
                if command == "use" and len(parts) > 1:
                    pipeline["uses"].extend(self._slug(part) for part in parts[1:])
                elif command == "header" and len(parts) > 2:
                    pipeline["headers"][" ".join(parts[1:-1])] = parts[-1]
                elif command == "cors":
                    pipeline["cors"] = parts[1] if len(parts) > 1 else "*"
                elif command == "log" and len(parts) > 1:
                    pipeline["log"] = bool(self._coerce_value(parts[1]))
                elif command == "request_id" and len(parts) > 1:
                    pipeline["request_id"] = bool(self._coerce_value(parts[1]))
                elif command == "require_header" and len(parts) > 2:
                    pipeline["require_headers"].append(self._require_header(parts[1:]))
            self.pipelines.append(pipeline)
            return ""

        if kind == "guard":
            guard: dict[str, object] = {"name": self._slug(name), "path": name if name.startswith("/") else "", "token": ""}
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower()
                if command == "path" and len(parts) > 1:
                    guard["path"] = parts[1]
                elif command == "token" and len(parts) > 1:
                    guard["token"] = parts[1]
            if guard["path"]:
                self.guards.append(guard)
            return ""

        if kind == "container":
            selector = ".cpj-section"
            min_width = "420px"
            rules: list[str] = []
            container_name = self._slug(name)
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower().replace("-", "_")
                if command == "selector" and len(parts) > 1:
                    selector = parts[1]
                elif command in {"min", "min_width"} and len(parts) > 1:
                    min_width = parts[1]
                elif command in {"css", "rule"} and len(parts) > 1:
                    rules.append(" ".join(parts[1:]))
            self.custom_css.append(f"{selector} {{ container-type: inline-size; container-name: {container_name}; }}")
            if rules:
                self.custom_css.append(f"@container {container_name} (min-width: {min_width}) {{ {' '.join(rules)} }}")
            return ""

        if kind == "animation":
            animation_name = self._slug(name).replace("-", "_")
            duration = "320ms"
            timing = "ease"
            from_rule = "opacity: 0;"
            to_rule = "opacity: 1;"
            apply_selector = ""
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower()
                if command == "duration" and len(parts) > 1:
                    duration = parts[1]
                elif command == "timing" and len(parts) > 1:
                    timing = parts[1]
                elif command == "from" and len(parts) > 1:
                    from_rule = " ".join(parts[1:])
                elif command == "to" and len(parts) > 1:
                    to_rule = " ".join(parts[1:])
                elif command == "apply" and len(parts) > 1:
                    apply_selector = parts[1]
            self.custom_css.append(f"@keyframes {animation_name} {{ from {{ {from_rule} }} to {{ {to_rule} }} }}")
            if apply_selector:
                self.custom_css.append(f"{apply_selector} {{ animation: {animation_name} {duration} {timing} both; }}")
            return ""

        if kind == "bundle":
            bundle_name = self._slug(name)
            bundle: dict[str, object] = {
                "name": bundle_name,
                "target": "es2022",
                "module": "esm",
                "types": True,
                "exports": ["CPJ"],
            }
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower()
                if command in {"target", "module"} and len(parts) > 1:
                    bundle[command] = parts[1]
                elif command == "types" and len(parts) > 1:
                    bundle["types"] = bool(self._coerce_value(parts[1]))
                elif command == "export" and len(parts) > 1:
                    bundle.setdefault("exports", [])
                    bundle["exports"].extend(parts[1:])
            self.bundle = bundle
            return ""

        if kind == "marketplace":
            marketplace = {
                "name": " ".join(tokens[1:]) if len(tokens) > 1 else "CPJ Marketplace",
                "registry": "local",
                "plugins": [],
                "hooks": {},
            }
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower()
                if command == "registry" and len(parts) > 1:
                    marketplace["registry"] = parts[1]
                elif command == "plugin" and len(parts) > 3:
                    marketplace["plugins"].append(
                        {
                            "slug": self._slug(parts[1]),
                            "name": parts[2],
                            "version": parts[3],
                            "description": " ".join(parts[4:]) if len(parts) > 4 else "",
                            "status": "active",
                        }
                    )
                elif command == "hook" and len(parts) > 3:
                    plugin = self._slug(parts[1])
                    hook_name = self._slug(parts[2])
                    marketplace["hooks"].setdefault(hook_name, [])
                    marketplace["hooks"][hook_name].append({"plugin": plugin, "html": " ".join(parts[3:])})
            self.marketplace = marketplace
            return ""

        if kind == "cms":
            config: dict[str, object] = {
                "name": name,
                "admin_path": "/admin",
                "blog_path": "/blog",
                "storage": f"{self._slug(name)}_content.json",
                "posts": [],
                "pages": [],
                "categories": [],
                "comments": [],
                "media": [],
                "users": [],
                "plugins": [],
                "settings": {},
            }
            for line in raw_lines:
                parts = self._split(line)
                if not parts:
                    continue
                command = parts[0].lower()
                if command == "admin" and len(parts) > 1:
                    config["admin_path"] = parts[1]
                elif command == "blog" and len(parts) > 1:
                    config["blog_path"] = parts[1]
                elif command == "storage" and len(parts) > 1:
                    config["storage"] = parts[1]
                elif command == "site" and len(parts) > 1:
                    config["name"] = " ".join(parts[1:])
                elif command == "category" and len(parts) > 1:
                    config["categories"].append(" ".join(parts[1:]))
                elif command == "setting" and len(parts) > 2:
                    config["settings"][self._slug(parts[1])] = self._coerce_value(" ".join(parts[2:]))
                elif command == "user" and len(parts) > 3:
                    username = self._slug(parts[1])
                    password = parts[2]
                    config["users"].append(
                        {
                            "username": username,
                            "display_name": " ".join(parts[4:]) if len(parts) > 4 else username,
                            "role": parts[3],
                            "password_hash": self._cms_password_hash(username, password),
                        }
                    )
                elif command == "post" and len(parts) > 3:
                    config["posts"].append(
                        {
                            "slug": self._slug(parts[1]),
                            "title": parts[2],
                            "body": " ".join(parts[3:]),
                            "type": "post",
                            "status": "published",
                            "author": "CPJ",
                        }
                    )
                elif command == "page" and len(parts) > 3:
                    config["pages"].append(
                        {
                            "slug": self._slug(parts[1]),
                            "title": parts[2],
                            "body": " ".join(parts[3:]),
                            "type": "page",
                            "status": "published",
                            "author": "CPJ",
                        }
                    )
                elif command == "comment" and len(parts) > 3:
                    config["comments"].append(
                        {
                            "id": f"seed-{len(config['comments']) + 1}",
                            "post": self._slug(parts[1]),
                            "author": parts[2],
                            "body": " ".join(parts[3:]),
                            "status": "approved",
                        }
                    )
                elif command == "media" and len(parts) > 3:
                    config["media"].append(
                        {
                            "slug": self._slug(parts[1]),
                            "title": parts[2],
                            "url": parts[3],
                            "alt": " ".join(parts[4:]) if len(parts) > 4 else parts[2],
                        }
                    )
                elif command == "plugin" and len(parts) > 2:
                    config["plugins"].append(
                        {
                            "slug": self._slug(parts[1]),
                            "name": parts[2],
                            "description": " ".join(parts[3:]) if len(parts) > 3 else "",
                            "status": "active",
                        }
                    )
            self.cms = config
            return ""

        return ""

    def _emit_statement(self, line: str, context: str | None = None) -> str:
        tokens = self._split(line)
        if not tokens:
            return ""

        kind = tokens[0].lower()

        if kind == "title" and len(tokens) > 1:
            self.title = " ".join(tokens[1:])
            return ""

        if kind == "meta" and len(tokens) > 2:
            if tokens[1].lower() == "description":
                self.description = " ".join(tokens[2:])
            return ""

        if kind == "pwa":
            name = " ".join(tokens[1:]) if len(tokens) > 1 else self.title
            self.pwa = {
                "name": name or self.title,
                "short_name": (name or self.title)[:24],
                "start_url": "/",
                "display": "standalone",
            }
            return ""

        if kind in {"theme", "style"} and len(tokens) > 2:
            key = tokens[1].replace("-", "_")
            self.theme[key] = tokens[2]
            return ""

        if kind == "server" and len(tokens) > 2:
            option = tokens[1].lower()
            if option == "host":
                self.server_host = tokens[2]
            elif option == "port":
                self.server_port = int(tokens[2])
            return ""

        if kind == "css" and len(tokens) > 1:
            self.custom_css.append(" ".join(tokens[1:]))
            return ""

        if kind in {"js", "javascript"} and len(tokens) > 1:
            self.custom_js.append(" ".join(tokens[1:]))
            return ""

        if kind == "html" and len(tokens) > 1:
            return " ".join(tokens[1:])

        if kind == "state" and len(tokens) > 2:
            self.states[self._slug(tokens[1])] = " ".join(tokens[2:])
            return ""

        if kind == "slot":
            slot_name = self._slug(tokens[1]) if len(tokens) > 1 else "content"
            return "{{" + slot_name + "}}"

        if kind == "nav" and len(tokens) > 2:
            self.nav_items.append((tokens[1], tokens[2]))
            return ""

        if kind in {"h1", "h2", "h3", "h4", "p", "small", "code"}:
            tag = "p" if kind == "small" else kind
            css = "cpj-small" if kind == "small" else None
            if kind == "h1":
                self.seen_h1 += 1
            return self._tag(tag, " ".join(tokens[1:]), css)

        if kind == "text":
            return self._tag("p", " ".join(tokens[1:]))

        if kind == "badge" and len(tokens) > 1:
            return self._tag("span", " ".join(tokens[1:]), "cpj-badge")

        if kind == "link" and len(tokens) > 2:
            return self._link(tokens[1], tokens[2], "cpj-link")

        if kind == "use" and len(tokens) > 1:
            component_name = self._slug(tokens[1])
            return self.components.get(
                component_name,
                f"<!-- CPJ web: missing component {self._text(tokens[1])} -->",
            )

        if kind == "button" and len(tokens) > 1:
            label = tokens[1]
            target = self._target_from_tokens(tokens[2:])
            if target:
                return self._link(label, target, "cpj-button")
            button_type = "submit" if context == "form" else "button"
            return self._tag(
                "button",
                label,
                "cpj-button",
                {"type": button_type, "data-cpj-action": self._slug(label)},
            )

        if kind == "card" and len(tokens) > 2:
            return self._block(
                "article",
                [self._tag("h3", tokens[1]), self._tag("p", " ".join(tokens[2:]))],
                {"class": "cpj-card"},
            )

        if kind == "image" and len(tokens) > 1:
            src = tokens[1]
            alt = tokens[2] if len(tokens) > 2 else ""
            if not alt:
                self.diagnostics_messages.append(
                    {
                        "level": "warning",
                        "area": "accessibility",
                        "message": f"Image {src} is missing alt text.",
                    }
                )
            return f'<img class="cpj-image" src="{self._attr(src)}" alt="{self._attr(alt)}">'

        if kind == "input" and len(tokens) > 2:
            name = self._slug(tokens[1])
            label = tokens[2]
            input_type = tokens[3] if len(tokens) > 3 else "text"
            return self._field(name, label, input_type, tokens[4:])

        if kind == "textarea" and len(tokens) > 2:
            name = self._slug(tokens[1])
            label = tokens[2]
            attrs = {"id": name, "name": name}
            self._apply_field_flags(attrs, tokens[3:])
            return (
                f'<label class="cpj-field" for="{self._attr(name)}">'
                f"<span>{self._text(label)}</span>"
                f"<textarea{self._attrs(attrs)}></textarea>"
                "</label>"
            )

        if kind == "select" and len(tokens) > 3:
            name = self._slug(tokens[1])
            label = tokens[2]
            attrs = {"id": name, "name": name}
            options_start = 3
            if len(tokens) > 4 and tokens[3].lower() == "required":
                self._apply_field_flags(attrs, ["required"])
                options_start = 4
            options = "\n".join(
                f'<option value="{self._attr(option)}">{self._text(option)}</option>'
                for option in tokens[options_start:]
            )
            return (
                f'<label class="cpj-field" for="{self._attr(name)}">'
                f"<span>{self._text(label)}</span>"
                f"<select{self._attrs(attrs)}>{options}</select>"
                "</label>"
            )

        if kind == "list" and len(tokens) > 1:
            items = "\n".join(f"<li>{self._text(item)}</li>" for item in tokens[1:])
            return f'<ul class="cpj-list">{items}</ul>'

        if kind == "counter" and len(tokens) > 2:
            name = self._slug(tokens[1])
            label = tokens[2]
            initial = tokens[3] if len(tokens) > 3 else "0"
            return self._counter(name, label, initial)

        return f"<!-- CPJ web: ignored line {self._text(line)} -->"

    def _document(self) -> str:
        nav = self._nav()
        state_script = "\n".join(
            f"  CPJ.state[{key!r}] = {value!r};" for key, value in self.states.items()
        )
        body = "\n".join(self.body_parts)
