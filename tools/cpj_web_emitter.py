def init_stores():
    if not STORES and not MIGRATIONS:
        return
    db = sqlite3.connect(STORE_DB)
    try:
        for name, store in STORES.items():
            table_name = safe_identifier(name)
            fields = store.get("fields", [])
            columns = ["id INTEGER PRIMARY KEY AUTOINCREMENT", "created_at TEXT NOT NULL"]
            for field in fields:
                field_name = safe_identifier(field["name"])
                required = " NOT NULL" if field.get("required") else ""
                columns.append(f"{{field_name}} {{sql_type(field.get('type', 'text'))}}{{required}}")
            db.execute(f"CREATE TABLE IF NOT EXISTS {{table_name}} ({{', '.join(columns)}})")
        apply_migrations(db)
        for name, store in STORES.items():
            table_name = safe_identifier(name)
            count = db.execute(f"SELECT COUNT(*) FROM {{table_name}}").fetchone()[0]
            if count == 0:
                for row in store.get("seed", []):
                    store_create(name, row, db=db)
        db.commit()
    finally:
        db.close()


def store_create(name, data, db=None):
    close = db is None
    db = db or sqlite3.connect(STORE_DB)
    try:
        store = STORES[name]
        table_name = safe_identifier(name)
        fields = [safe_identifier(field["name"]) for field in store.get("fields", [])]
        row = {{"created_at": datetime.now(timezone.utc).isoformat()}}
        for field in fields:
            row[field] = data.get(field, "")
        columns = list(row.keys())
        placeholders = ", ".join("?" for _ in columns)
        db.execute(
            f"INSERT INTO {{table_name}} ({{', '.join(columns)}}) VALUES ({{placeholders}})",
            [row[column] for column in columns],
        )
        row["id"] = db.execute("SELECT last_insert_rowid()").fetchone()[0]
        if close:
            db.commit()
        return row
    finally:
        if close:
            db.close()


def store_rows(name):
    db = sqlite3.connect(STORE_DB)
    db.row_factory = sqlite3.Row
    try:
        table_name = safe_identifier(name)
        rows = db.execute(f"SELECT * FROM {{table_name}} ORDER BY id DESC").fetchall()
        return [dict(row) for row in rows]
    finally:
        db.close()


def store_update(name, row_id, data):
    db = sqlite3.connect(STORE_DB)
    db.row_factory = sqlite3.Row
    try:
        table_name = safe_identifier(name)
        fields = [safe_identifier(field["name"]) for field in STORES[name].get("fields", []) if field["name"] in data]
        if fields:
            assignments = ", ".join(f"{{field}} = ?" for field in fields)
            db.execute(f"UPDATE {{table_name}} SET {{assignments}} WHERE id = ?", [data[field] for field in fields] + [row_id])
            db.commit()
        row = db.execute(f"SELECT * FROM {{table_name}} WHERE id = ?", [row_id]).fetchone()
        return dict(row) if row else None
    finally:
        db.close()


def store_delete(name, row_id):
    db = sqlite3.connect(STORE_DB)
    try:
        table_name = safe_identifier(name)
        db.execute(f"DELETE FROM {{table_name}} WHERE id = ?", [row_id])
        db.commit()
    finally:
        db.close()
    return {{"deleted": True, "id": row_id}}


